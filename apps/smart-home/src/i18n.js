export const t = (s) => {
  if (document.documentElement.lang !== "ar") return s;
  if (ar[s]) return ar[s];
  const open = /^(\d+)% open$/.exec(s);
  return open ? `${n(Number(open[1]))}٪ مفتوحة` : s;
};
export const n = (v, d = 0) =>
  new Intl.NumberFormat(
    document.documentElement.lang === "ar" ? "ar-EG" : "en-GB",
    { maximumFractionDigits: d },
  ).format(v);
