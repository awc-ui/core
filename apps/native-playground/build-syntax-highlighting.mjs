import { createRequire } from 'node:module';
import { readFile, writeFile, mkdir, realpath } from 'node:fs/promises';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const directory = dirname(fileURLToPath(import.meta.url));
const repository = resolve(directory, '../..');
const roots = [repository];
try { roots.push(dirname(await realpath(join(repository, 'node_modules')))); } catch { /* Regular workspace install. */ }
let shiki, esbuild;
for (const root of roots) {
  try { const require = createRequire(join(root, 'apps/docs/package.json')); require.resolve('shiki/core'); shiki ||= require; } catch { /* Try the shared install. */ }
  try { esbuild ||= createRequire(join(root, 'packages/theme/package.json'))('esbuild'); } catch { /* Try the shared install. */ }
}
if (!shiki || !esbuild) throw new Error('Install the existing workspace dependencies before building syntax highlighting. This script does not download packages.');
const languages = ['html', 'tsx', 'typescript', 'vue', 'svelte', 'swift', 'kotlin', 'javascript', 'json', 'css', 'bash'];
const themes = ['github-light', 'github-dark'];
const imports = [
  `import { createHighlighterCore } from ${JSON.stringify(shiki.resolve('shiki/core'))};`,
  `import { createJavaScriptRegexEngine } from ${JSON.stringify(shiki.resolve('shiki/engine/javascript'))};`,
  ...languages.map((name, index) => `import lang${index} from ${JSON.stringify(shiki.resolve(`shiki/langs/${name}.mjs`))};`),
  ...themes.map((name, index) => `import theme${index} from ${JSON.stringify(shiki.resolve(`shiki/themes/${name}.mjs`))};`),
];
const entry = `${imports.join('\n')}
const ready = createHighlighterCore({ engine: createJavaScriptRegexEngine(), langs: [${languages.map((_, i) => `lang${i}`).join(',')}], themes: [theme0, theme1] });
export async function tokens(code, lang) { return (await ready).codeToTokensWithThemes(code, { lang, themes: { light: 'github-light', dark: 'github-dark' } }); }
`;
const output = join(directory, 'syntax-vendor/highlighter.js');
const result = await esbuild.build({ stdin: { contents: entry, resolveDir: directory, sourcefile: 'studio-syntax-entry.js' }, bundle: true, format: 'esm', platform: 'browser', target: 'es2020', minify: true, legalComments: 'inline', metafile: true, write: false, outfile: output,
  banner: { js: '// Generated by build-syntax-highlighting.mjs from locally installed Shiki. See LICENSES.txt.' } });
const licenses = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!resolve(input).includes(`${join('node_modules', '')}/`)) continue;
  let current = dirname(resolve(input));
  while (current !== dirname(current)) {
    try {
      const pkg = JSON.parse(await readFile(join(current, 'package.json'), 'utf8'));
      if (!pkg.name) { current = dirname(current); continue; }
      if (!licenses.has(pkg.name)) {
        let license = '';
        for (const name of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license']) { try { license = await readFile(join(current, name), 'utf8'); break; } catch { /* Try conventional filenames. */ } }
        if (!license) throw new Error(`Missing license for bundled ${pkg.name}.`);
        licenses.set(pkg.name, `${pkg.name}@${pkg.version}\n${license.trim()}`);
      }
      break;
    } catch (error) { if (error.message.startsWith('Missing license')) throw error; current = dirname(current); }
  }
}
const outputs = new Map([[output, result.outputFiles[0].text], [join(dirname(output), 'LICENSES.txt'), [...licenses].sort(([a], [b]) => a.localeCompare(b)).map(([, license]) => license).join('\n\n') + '\n']]);
for (const [file, contents] of outputs) {
  if (process.argv.includes('--check')) { if (await readFile(file, 'utf8') !== contents) throw new Error('Syntax bundle is stale. Run node apps/native-playground/build-syntax-highlighting.mjs.'); }
  else { await mkdir(dirname(file), { recursive: true }); await writeFile(file, contents); }
}
console.log(process.argv.includes('--check') ? 'Studio syntax bundle is current.' : `Built syntax-vendor/highlighter.js (${result.outputFiles[0].contents.length} bytes).`);
