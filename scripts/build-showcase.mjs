#!/usr/bin/env node
/**
 * Build every framework build of every showcase vertical, and stage the output
 * where the docs site serves it from.
 *
 * WHY THIS EXISTS. Each build emits into a different directory — Next writes
 * `out/`, SvelteKit `build/`, Nuxt `.output/public/`, Angular `dist/browser/`,
 * Astro and the plain-HTML build `dist/` — and each is compiled against an
 * absolute base path of `/showcase/credit-risk/<framework>/`. So every asset
 * URL, every link and every runtime import in the output already carries that
 * prefix, which means the output only works when it is sitting at exactly that
 * path. Copying it there is the whole job.
 *
 * `apps/docs/public/showcase/` is gitignored for the same reason the Storybook
 * output and the Stencil runtime are: it is build output, it churns on every
 * rebuild, and a committed copy can go stale against the library it demonstrates.
 * It has to be regenerated by the pipeline, which is what this does.
 *
 * Every build needs `packages/core/dist` to exist first — each one copies
 * Stencil's lazy runtime out of it — so `scripts/build-docs.sh` calls this
 * AFTER the core build and BEFORE `astro build`, which is the point at which
 * `public/` is read.
 */
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * One entry per framework build. `output` is where that toolchain writes, and
 * it is the only thing that differs between them — the mount path is derived
 * from the framework id, exactly as `createRoutes()` does inside each app.
 */
const VERTICAL = 'credit-risk';
const BUILDS = [
  { framework: 'html', pkg: '@awc-ui/showcase-credit-risk-html', output: 'dist' },
  { framework: 'astro', pkg: '@awc-ui/showcase-credit-risk-astro', output: 'dist' },
  { framework: 'react', pkg: '@awc-ui/showcase-credit-risk-react', output: 'out' },
  { framework: 'vue', pkg: '@awc-ui/showcase-credit-risk-vue', output: '.output/public' },
  { framework: 'angular', pkg: '@awc-ui/showcase-credit-risk-angular', output: 'dist/browser' },
  { framework: 'svelte', pkg: '@awc-ui/showcase-credit-risk-svelte', output: 'build' },
];

/** Only build the frameworks named on the command line, if any are. */
const wanted = process.argv.slice(2);
const builds = wanted.length ? BUILDS.filter((b) => wanted.includes(b.framework)) : BUILDS;

if (!builds.length) {
  console.error(
    `[build-showcase] no such framework: ${wanted.join(', ')}\n` +
      `                known: ${BUILDS.map((b) => b.framework).join(', ')}`,
  );
  process.exit(1);
}

if (!existsSync(join(root, 'packages/core/dist/md3'))) {
  console.error(
    '[build-showcase] packages/core/dist/md3 does not exist — build core first:\n' +
      '                pnpm --filter @awc-ui/core build',
  );
  process.exit(1);
}

/* Every showcase app imports @awc-ui/showcase-kit's COMPILED dist (data,
   credit-risk, i18n, dock, preboot), so the kit has to exist before any of
   them build. Building it here rather than guarding on it: it is a couple of
   seconds, and a guard only converts one confusing failure
   ("ERR_MODULE_NOT_FOUND: .../showcase-kit/dist/data/index.mjs", six levels
   deep in a per-app build) into a slightly less confusing one. This is the
   single entry point every caller uses — the deploy workflow, CI, and a
   developer running it by hand — so fixing it here fixes it for all of them. */
console.log('==> showcase-kit');
const kit = spawnSync('pnpm', ['--filter', '@awc-ui/showcase-kit', 'build'], {
  cwd: root,
  stdio: 'inherit',
  shell: false,
});
if (kit.status !== 0) {
  console.error('[build-showcase] @awc-ui/showcase-kit failed — the apps import its dist');
  process.exit(1);
}

const staging = join(root, 'apps/docs/public/showcase', VERTICAL);
mkdirSync(staging, { recursive: true });

function bytes(dir) {
  let total = 0;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    total += entry.isDirectory() ? bytes(full) : statSync(full).size;
  }
  return total;
}

function pages(dir) {
  let total = 0;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) total += pages(join(dir, entry.name));
    else if (entry.name.endsWith('.html')) total += 1;
  }
  return total;
}

for (const build of builds) {
  console.log(`\n==> ${VERTICAL} / ${build.framework}`);
  const result = spawnSync('pnpm', ['--filter', build.pkg, 'build'], {
    cwd: root,
    stdio: 'inherit',
    shell: false,
  });
  if (result.status !== 0) {
    console.error(`[build-showcase] ${build.pkg} failed`);
    process.exit(result.status ?? 1);
  }

  const from = join(root, 'apps/showcase', VERTICAL, build.framework, build.output);
  if (!existsSync(from)) {
    console.error(`[build-showcase] ${build.pkg} built but ${build.output}/ is missing`);
    process.exit(1);
  }

  const to = join(staging, build.framework);
  if (existsSync(to)) rmSync(to, { recursive: true });
  cpSync(from, to, { recursive: true });

  console.log(
    `    -> apps/docs/public/showcase/${VERTICAL}/${build.framework} — ` +
      `${pages(to)} pages, ${(bytes(to) / 1024 / 1024).toFixed(1)} MB`,
  );
}

console.log(`\n[build-showcase] ${builds.length} build(s) staged under apps/docs/public/showcase/`);
