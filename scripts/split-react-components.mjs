#!/usr/bin/env node
/**
 * split-react-components — one module per React wrapper, for robust tree-shaking.
 *
 * The Stencil React Output Target generates a single packages/react/src/components.ts
 * barrel that imports all ~90 custom-element modules from @awc-ui/core. Even with
 * "sideEffects" declared, that shape leaves consumers one bundler misconfiguration
 * away from shipping the whole library, and it defeats subpath imports entirely.
 *
 * This script runs after `stencil build` (chained in @awc-ui/core's "build" script,
 * after fix-module-types.mjs) and rewrites the generated output:
 *
 *   src/components.ts             -> a pure re-export barrel (public API unchanged)
 *   src/components/<Name>.ts      -> that component's element import, Events type
 *                                    and createComponent block, self-contained
 *
 * Consumers can then use either form:
 *   import { MdButton } from '@awc-ui/react'                       (barrel, shaken)
 *   import { MdButton } from '@awc-ui/react/components/MdButton'   (never bloats)
 *
 * Idempotent: if components.ts is already the generated barrel (marker below),
 * the split is skipped. components.server.ts is left untouched — the SSR wrappers
 * run in Node where bundle size is not a concern.
 */
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const BARREL_MARKER = '/* barrel generated by scripts/split-react-components.mjs */';

const repoRoot = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(repoRoot, 'packages/react/src');
const componentsFile = path.join(srcDir, 'components.ts');
const outDir = path.join(srcDir, 'components');

const source = fs.readFileSync(componentsFile, 'utf8');
if (source.includes(BARREL_MARKER)) {
  console.log('split-react-components: components.ts is already a barrel, nothing to do');
  process.exit(0);
}

const lines = source.split('\n');

// ---- 1. Partition the file into header imports and component blocks ----------

// Element imports: import { MdX as MdXElement, defineCustomElement as defineMdX } from "@awc-ui/core/dist/components/md-x.js";
const elementImports = new Map(); // component name -> full import line
// The single big `import { type A, type B, ... } from "@awc-ui/core";` type list
let coreTypeNames = [];

let bodyStart = 0;
for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  const el = line.match(/^import \{ (Md\w+) as \1Element, defineCustomElement as define\1 \} from "(@awc-ui\/core\/dist\/components\/[\w-]+\.js)";$/);
  if (el) {
    elementImports.set(el[1], line);
    bodyStart = i + 1;
    continue;
  }
  const types = line.match(/^import \{ (type .+) \} from "@awc-ui\/core";$/);
  if (types) {
    coreTypeNames = types[1].split(',').map(s => s.trim().replace(/^type /, '')).filter(Boolean);
    bodyStart = i + 1;
    continue;
  }
  if (/^import /.test(line)) bodyStart = i + 1;
}

// ---- 2. Split the body into per-component chunks -----------------------------

// A component section starts at `export type <Name>Events =` or `export const <Name>:`,
// whichever appears first for that name. Everything until the next section belongs to it.
const body = lines.slice(bodyStart);
const sections = []; // { name, lines: [] }
let current = null;
for (const line of body) {
  const start = line.match(/^export (?:type (Md\w+)Events|const (Md\w+):)/);
  const name = start && (start[1] || start[2]);
  if (name && (!current || current.name !== name)) {
    current = { name, lines: [] };
    sections.push(current);
  }
  if (current) current.lines.push(line);
}

if (sections.length === 0) {
  console.error('split-react-components: no component blocks found in components.ts — generator output changed?');
  process.exit(1);
}
const missing = sections.filter(s => !elementImports.has(s.name)).map(s => s.name);
if (missing.length) {
  console.error(`split-react-components: no element import matched for: ${missing.join(', ')}`);
  process.exit(1);
}

// ---- 3. Emit one file per component ------------------------------------------

const FILE_HEADER = `'use client';

/**
 * Generated by scripts/split-react-components.mjs from the Stencil React Output
 * Target's components.ts. Do not edit — regenerated on every core build.
 */

/* eslint-disable */
`;

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

for (const section of sections) {
  const chunk = section.lines.join('\n').trim();
  const usedTypes = coreTypeNames.filter(t => new RegExp(`\\b${t}\\b`).test(chunk));
  const coreTypesImport = usedTypes.length
    ? `import type { ${usedTypes.join(', ')} } from "@awc-ui/core";\n`
    : '';
  const content = `${FILE_HEADER}
import type { EventName, StencilReactComponent } from '@stencil/react-output-target/runtime';
import { createComponent } from '@stencil/react-output-target/runtime';
import React from 'react';
${coreTypesImport}import type { Components } from "@awc-ui/core/dist/components";
${elementImports.get(section.name)}

${chunk}
`;
  fs.writeFileSync(path.join(outDir, `${section.name}.ts`), content);
}

// ---- 4. Rewrite components.ts as a pure re-export barrel ---------------------

const barrel = `'use client';

/**
 * Generated by scripts/split-react-components.mjs. Do not edit — regenerated on
 * every core build. Each component lives in its own module under ./components/
 * so bundlers only ever pull in what is imported.
 */
${BARREL_MARKER}

${sections.map(s => `export * from './components/${s.name}.js';`).join('\n')}
`;
fs.writeFileSync(componentsFile, barrel);

console.log(`split-react-components: split ${sections.length} components into packages/react/src/components/`);
